const Glyph& find(char c) {
    c = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
    for (const Glyph& g : kGlyphs)
        if (g.c == c) return g;
    for (const Glyph& g : kGlyphs)
        if (g.c == '?') return g;
    return kGlyphs[0];
}

