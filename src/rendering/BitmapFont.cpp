TextPixels rasterizeText(const std::string& text) {
    TextPixels out;
    out.height = kGlyphHeight;
    int cursor = 0;
    for (char ch : text) {
        const Glyph& g = find(ch);
        for (int row = 0; row < kGlyphHeight; ++row)
            for (int col = 0; col < 5; ++col)
                if (g.rows[row][col] == '#') out.pixels.emplace_back(cursor + col, row);
        cursor += kGlyphAdvance;
    }
    out.width = cursor > 0 ? cursor - 1 : 0;
    return out;
}
